def _clean(value) -> str:
    return str(value).replace(" ", " ").strip()


def _int(value, where: str) -> int:
    if value is None:
        raise SystemExit(
            f"{where}: empty cached value; open the workbook in Excel/Sheets and re-save"
        )
    return int(round(float(value)))


def read_classes(ws) -> list[dict]:
    out = []
    for row in ws.iter_rows(min_row=3, min_col=1, max_col=3, values_only=True):
        name, points, size = row
        if not name:
            break
        out.append(
            {"name": _clean(name), "size": SIZE_CODES[_clean(size)], "points": _int(points, name)}
        )
    return out


def read_hulls(ws) -> list[tuple[str, str, int]]:
    out = []
    for row in ws.iter_rows(min_row=3, min_col=6, max_col=8, values_only=True):
        hull, cls, points = row
        if not hull or _clean(hull) == "-":
            continue
        out.append((_clean(hull), _clean(cls), _int(points, hull)))
    return out


def read_hull_sizes(ws) -> list[dict]:
    out = []
    for row in ws.iter_rows(min_row=8, max_row=17, min_col=10, max_col=13, values_only=True):
        label, _short, limit, surcharge = row
        size = SIZE_CODES[_clean(label)]
        entry = {"size": size, "label": _clean(label), "max_per_comp": _int(limit, label)}
        if size != "FLAG":
            entry["duplicate_surcharge"] = _int(surcharge, label)
        out.append(entry)
    return out


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--workbook", type=Path, default=None)
    parser.add_argument(
        "--out", type=Path, default=BACKEND / "fixtures" / "rulesets" / "atxxii.yaml"
    )
    args = parser.parse_args()
    workbook = args.workbook or Path(
        next(iter(glob.glob(str(BACKEND.parent / "docs" / "research" / "*.xlsx"))))
    )

    wb = openpyxl.load_workbook(workbook, read_only=True, data_only=True)
    classes = read_classes(wb["Point values"])
    hulls = read_hulls(wb["Point values"])
    hull_sizes = read_hull_sizes(wb["Configurables"])

    class_points = {c["name"]: c["points"] for c in classes}
    overrides = [{"hull": h, "points": p} for h, cls, p in hulls if class_points.get(cls) != p]
    missing = [cls for _, cls, _ in hulls if cls not in class_points]
    if missing:
        raise SystemExit(
            f"hull table references classes not in the class table: {sorted(set(missing))}"
        )

    ships = []
    for hull, cls, _ in hulls:
        entry: dict = {"hull": hull, "class": cls}
        if hull in FLAGSHIP_INELIGIBLE:
            entry["flagship_eligible"] = False
        ships.append(entry)

    doc = yaml_io.RulesetDocument.model_validate(
        {
            "schema_version": yaml_io.SCHEMA_VERSION,
            "verified": True,
            "notes": NOTES,
            "tournament": TOURNAMENT,
            "ruleset": RULESET,
            "hull_sizes": hull_sizes,
            "group_limits": GROUP_LIMITS,
            "stages": STAGES,
            "ship_classes": classes,
            "ships": ships,
            "point_table": {
                "label": "Workbook import (community Quick Comp Creator values)",
                "source_url": "https://docs.google.com/spreadsheets/d/1AVYlWlvuMKnA3yuqqDCcAkia8pvhpb9OBcM29WFw5rM",
                "effective_from": "2026-08-01",
                "hull_overrides": overrides,
            },
            "banned_hulls": BANNED_HULLS,
            "unique_hulls": UNIQUE_HULLS,
            "module_rules": MODULE_RULES,
            "text_sections": TEXT_SECTIONS,
        }
    )

    by_hull = {s["hull"]: class_points[s["class"]] for s in ships}
    sizes = {c["name"]: c["size"] for c in classes}
    hull_size = {s["hull"]: sizes[s["class"]] for s in ships}
    assert by_hull["Astarte"] == 33 and by_hull["Deacon"] == 10 and by_hull["Ashimmu"] == 18, (
        by_hull
    )
    for name in ("Bantam", "Burst", "Inquisitor", "Navitas"):
        assert hull_size[name] == "LF", (name, hull_size[name])
    for name in ("Augoror", "Osprey", "Exequror", "Scythe"):
        assert hull_size[name] == "LC", (name, hull_size[name])

    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(yaml_io.dump_document(doc), encoding="utf-8")
    print(
        f"wrote {args.out}: {len(classes)} classes, {len(ships)} ships, {len(overrides)} hull overrides"
    )


if __name__ == "__main__":
    main()
